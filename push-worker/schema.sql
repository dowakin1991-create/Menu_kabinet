CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, uid TEXT NOT NULL, subscription TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS devices_uid ON devices(uid);
CREATE TRIGGER IF NOT EXISTS devices_limit BEFORE INSERT ON devices
WHEN (SELECT COUNT(*) FROM devices WHERE uid=NEW.uid AND id<>NEW.id)>=10
BEGIN SELECT RAISE(ABORT, 'DEVICE_LIMIT'); END;
CREATE TRIGGER IF NOT EXISTS devices_update_limit BEFORE UPDATE OF uid ON devices
WHEN (SELECT COUNT(*) FROM devices WHERE uid=NEW.uid AND id<>NEW.id)>=10
BEGIN SELECT RAISE(ABORT, 'DEVICE_LIMIT'); END;
CREATE TABLE IF NOT EXISTS rate (id TEXT PRIMARY KEY, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS jobs (id TEXT PRIMARY KEY, owner TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS deliveries (job TEXT NOT NULL, idx INTEGER NOT NULL, device TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending', PRIMARY KEY(job,idx));
